def localizar_particion(indice, filas):
    import socket

    cantidad = sum(1 for _ in filas)
    yield (indice, socket.gethostname(), cantidad)

(
    df.rdd
    .mapPartitionsWithIndex(localizar_particion)
    .toDF(["particion", "host", "filas"])
    .orderBy("particion")
    .show(truncate=False)
)

